window.getLang = () => {
  const saved = localStorage.getItem('trm_lang');
  return saved === 'tr' || saved === 'en' ? saved : 'en';
};

window.t = (key, vars = null) => {
  const lang = window.getLang();
  let s = (window.TRM_I18N[lang] && window.TRM_I18N[lang][key]) || window.TRM_I18N.en[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v ?? ''));
  }
  return s;
};

window.applyStaticI18n = () => {
  const lang = window.getLang();
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = window.t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = window.t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = window.t(el.dataset.i18nTitle);
  });
  const btnLang = document.getElementById('btn-lang');
  if (btnLang) btnLang.textContent = lang.toUpperCase();
  const landLang = document.getElementById('landing-lang');
  if (landLang) landLang.textContent = lang.toUpperCase();
};
